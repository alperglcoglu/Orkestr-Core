// Generated Markdown views and the status report. Views are derived from JSON records
// and are never edited by hand (MASTER_SPEC §16).

const banner = (id) =>
  `<!-- Generated by orkestr from ${id}.json. Do not edit; change the record through the orkestr state tool. -->\n`;

const list = (items, fmt = (x) => x) => (items?.length ? items.map((x) => `- ${fmt(x)}`).join('\n') : '- (none)');

export function renderMeeting(m) {
  const rounds = m.rounds
    .map(
      (r) =>
        `### Round ${r.round}\n\n` +
        r.contributions
          .map((c) => {
            const points = c.key_points?.length ? `\n${c.key_points.map((p) => `  - ${p}`).join('\n')}` : '';
            const concerns = c.concerns?.length ? `\n  - Concerns: ${c.concerns.join('; ')}` : '';
            return `- **${c.role}:** ${c.position}${points}${concerns}`;
          })
          .join('\n'),
    )
    .join('\n\n');
  return `${banner(m.id)}
# ${m.id} — ${m.objective}

- **Date:** ${m.date}
- **Outcome:** ${m.outcome}
- **Decision:** ${m.decision_id ?? '(none)'}
- **Tasks created:** ${m.task_ids.length ? m.task_ids.join(', ') : '(none)'}

## Why a meeting

${m.trigger}

## Context

${m.context}

## Participants

${list(m.participants, (p) => `**${p.role}** — ${p.responsibility}`)}

## Discussion

${rounds}

## Options

${list(m.options, (o) => `**${o.id} ${o.name}** — ${o.summary ?? ''}`)}

## Evaluation criteria

${list(m.criteria)}

## Evaluation

${m.evaluation || '(not recorded)'}

## Dissent

${list(m.dissent, (d) => `**${d.role}:** ${d.objection}`)}

## Open questions

${list(m.open_questions)}
`;
}

export function renderDecision(d) {
  const selected = d.options.find((o) => o.id === d.selected_option);
  return `${banner(d.id)}
# ${d.id} — ${d.question}

- **Date:** ${d.date}
- **Project:** ${d.project}
- **Approval status:** ${d.approval_status}${d.decided_by ? ` (by ${d.decided_by} at ${d.decided_at})` : ''}
- **Meeting:** ${d.meeting_id ?? '(none)'}${d.recovery_for ? ` (recovery for ${d.recovery_for})` : ''}
- **Founder required:** ${d.founder_required ? 'yes' : 'no'}
- **Participants:** ${d.participants.join(', ')}
- **Follow-up tasks:** ${d.task_ids.length ? d.task_ids.join(', ') : '(none)'}

## Context

${d.context}

## Options considered

${list(d.options, (o) => `**${o.id} ${o.name}** — ${o.summary ?? ''}`)}

## Evaluation criteria

${list(d.criteria)}

## Selected option

${selected ? `**${selected.id} ${selected.name}**` : '(none — waiting for the founder)'}

## Rationale

${d.rationale || '(not recorded)'}

## Trade-offs

${list(d.tradeoffs)}

## Material objections

${list(d.objections, (o) => `**${o.role}:** ${o.objection}`)}

## Risks

${list(d.risks)}
${d.note ? `\n## Founder note\n\n${d.note}\n` : ''}`;
}

export function renderReview(r) {
  const confirmed = r.findings.filter((f) => f.status === 'confirmed');
  const suspected = r.findings.filter((f) => f.status === 'suspected');
  const fmt = (f) =>
    `**[${f.severity}] ${f.title}**${f.component ? ` (${f.component})` : ''}\n  - Evidence: ${f.evidence}\n  - Recommendation: ${f.recommendation ?? '(none)'}`;
  return `${banner(r.id)}
# ${r.id} — Review: ${r.scope}

- **Date:** ${r.date}
- **Task:** ${r.task_id ?? '(none)'}
- **Reviewers:** ${r.reviewers.join(', ')}
- **Verdict:** ${r.verdict}

## Checks actually run

${list(r.checks_run, (c) => `\`${c.command}\` — ${c.result}${c.summary ? `: ${c.summary}` : ''}`)}

## Confirmed findings (verified)

${list(confirmed, fmt)}

## Suspected findings (not verified)

${list(suspected, fmt)}

## Assumptions

${list(r.assumptions)}
`;
}

export function renderRetro(r) {
  return `${banner(r.id)}
# ${r.id} — Retrospective: ${r.scope}

- **Date:** ${r.date}

## What went well

${list(r.went_well)}

## What went badly

${list(r.went_badly)}

## Incorrect assumptions

${list(r.incorrect_assumptions)}

## Was the decomposition appropriate?

${r.decomposition_assessment || '(not assessed)'}

## Did meetings improve decisions?

${r.meeting_assessment || '(not assessed)'}

## Lessons (with evidence)

${list(r.lessons, (l) => `${l.lesson} — evidence: ${l.evidence}`)}

## Proposed changes (not applied; need review)

${list(r.proposed_changes)}
`;
}

function assumptionLines(project) {
  const list = project.assumptions ?? [];
  return list.length
    ? list.map((a) => `- [${a.impact}] ${a.text}${a.task ? ` (${a.task})` : ''}`).join('\n')
    : '- (none)';
}

