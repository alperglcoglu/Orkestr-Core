// Completion report (autonomous mode): what a founder needs after a run, from saved artifacts only.

export function renderReport({ project, tasks, approvals, decisions, validation }) {
  const by = (s) => tasks.filter((t) => t.status === s);
  const out = [`# Orkestr completion report — ${project.name}`, ''];
  out.push(`- **Project status:** ${project.status}${project.status_reason ? ` — ${project.status_reason}` : ''}`);
  out.push(`- **Autonomy:** ${project.autonomy ?? 'supervised'}`);
  const counts = ['COMPLETED', 'IN_PROGRESS', 'REVIEW', 'READY', 'BACKLOG', 'BLOCKED', 'FAILED', 'CANCELLED']
    .map((s) => `${s} ${by(s).length}`)
    .join(', ');
  out.push(`- **Tasks:** ${counts} (total ${tasks.length})`, '');

  out.push('## What was done', '');
  out.push(by('COMPLETED').length ? by('COMPLETED').map((t) => `- ${t.id} — ${t.title} (owner: ${t.owner})`).join('\n') : '- (no completed tasks)');

  out.push('', '## Checks that actually ran', '');
  const runs = tasks.flatMap((t) =>
    t.evidence.filter((e) => ['test', 'check'].includes(e.type) && e.result !== 'not_run').map((e) => ({ t, e })),
  );
  out.push(runs.length ? runs.map(({ t, e }) => `- ${t.id}: \`${e.command}\` → ${e.result} — ${e.summary}`).join('\n') : '- (no checks recorded)');
  const notRun = tasks.flatMap((t) => t.evidence.filter((e) => e.result === 'not_run').map((e) => `- ${t.id}: not run — ${e.summary}`));
  if (notRun.length) out.push('', '### Not run', '', notRun.join('\n'));

  out.push('', '## Decisions', '');
  out.push(
    decisions.length
      ? decisions.map((d) => `- ${d.id} [${d.approval_status}${d.decided_by ? `, by ${d.decided_by}` : ''}] ${d.question}`).join('\n')
      : '- (none)',
  );

  out.push('', '## Assumptions', '', assumptionLines(project));

  out.push('', '## Unresolved', '');
  const open = [
    ...by('FAILED').map((t) => `- ${t.id} FAILED — ${t.failure?.error}; next: ${t.failure?.next_action}`),
    ...by('BLOCKED').map((t) => `- ${t.id} BLOCKED — ${t.blocked_reason}`),
    ...[...by('IN_PROGRESS'), ...by('REVIEW'), ...by('READY'), ...by('BACKLOG')].map((t) => `- ${t.id} ${t.status} — ${t.title}`),
  ];
  out.push(open.length ? open.join('\n') : '- (none)');

  out.push('', '## Needs the founder', '');
  const founder = [
    ...approvals.filter((a) => a.status === 'PENDING').map((a) => `- Approve or reject ${a.id} [${a.category}]: ${a.action}`),
    ...decisions
      .filter((d) => d.approval_status === 'PROPOSED' || d.approval_status === 'NEEDS_FOUNDER')
      .map((d) => `- Decide ${d.id}: ${d.question}`),
    ...by('FAILED')
      .filter((t) => /Founder/.test(t.failure?.next_action ?? ''))
      .map((t) => `- ${t.id} could not be fixed within limits: retry, change approach, or cancel`),
    ...tasks.filter((t) => !t.authorized && !['CANCELLED', 'COMPLETED'].includes(t.status)).map((t) => `- Authorize or drop ${t.id}: ${t.title}`),
  ];
  out.push(founder.length ? founder.join('\n') : '- Nothing.');

  out.push('', '## Validation', '');
  out.push(validation.errors.length ? validation.errors.map((e) => `- ERROR: ${e}`).join('\n') : '- OK');
  out.push('');
  return out.join('\n');
}

