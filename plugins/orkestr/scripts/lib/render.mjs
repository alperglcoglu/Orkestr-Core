// Status report (MASTER_SPEC §3, §14). Built only from saved artifacts.

export function renderStatus({ project, tasks, approvals, decisions, history, validation }) {
  const by = (s) => tasks.filter((t) => t.status === s);
  const line = (t) => `- ${t.id} — ${t.title} (owner: ${t.owner})`;
  const out = [];
  out.push(`# Orkestr status — ${project.name}`, '');
  out.push(`- **Project status:** ${project.status}${project.status_reason ? ` — ${project.status_reason}` : ''}`);
  out.push(`- **Goal:** ${project.goal}`);
  out.push(`- **Autonomy:** ${project.autonomy ?? 'supervised'}`);
  out.push(`- **Limits:** ${project.limits.max_meeting_participants} meeting participants, ${project.limits.max_discussion_rounds} discussion rounds, ${project.limits.max_fix_attempts} fix attempts, ${project.limits.max_recovery_meetings ?? 1} recovery meeting(s) per task, ${project.limits.max_parallel_tasks ?? 1} parallel task(s)`);
  out.push('');

  const states = ['BACKLOG', 'READY', 'IN_PROGRESS', 'BLOCKED', 'REVIEW', 'FAILED', 'COMPLETED', 'CANCELLED'];
  out.push('## Task counts', '', '| State | Count |', '| :- | -: |');
  for (const s of states) out.push(`| ${s} | ${by(s).length} |`);
  out.push(`| **Total** | ${tasks.length} |`, '');

  const pending = approvals.filter((a) => a.status === 'PENDING');
  const waiting = decisions.filter((d) => d.approval_status === 'PROPOSED' || d.approval_status === 'NEEDS_FOUNDER');
  const unauthorized = tasks.filter((t) => !t.authorized && !['CANCELLED', 'COMPLETED'].includes(t.status));
  out.push('## Needs founder attention', '');
  out.push('### Pending approvals', '');
  out.push(pending.length ? pending.map((a) => `- ${a.id} [${a.category}] ${a.action}${a.task_id ? ` (task ${a.task_id})` : ''} — reason: ${a.reason}`).join('\n') : '- (none)');
  out.push('', '### Decisions waiting for the founder', '');
  out.push(waiting.length ? waiting.map((d) => `- ${d.id} [${d.approval_status}] ${d.question}`).join('\n') : '- (none)');
  out.push('', '### Tasks waiting for authorization', '');
  out.push(
    unauthorized.length
      ? unauthorized.map((t) => `- ${t.id} — ${t.title} (source: ${t.source.type}${t.decision_id ? `, decision ${t.decision_id}` : ''})`).join('\n')
      : '- (none)',
  );
  out.push('');

  out.push('## Blocked', '');
  out.push(by('BLOCKED').length ? by('BLOCKED').map((t) => `${line(t)}\n  - Reason: ${t.blocked_reason}`).join('\n') : '- (none)');
  out.push('', '## Failed', '');
  out.push(
    by('FAILED').length
      ? by('FAILED').map((t) => `${line(t)}\n  - Error: ${t.failure?.error}\n  - Next action: ${t.failure?.next_action}`).join('\n')
      : '- (none)',
  );
  out.push('', '## In progress', '');
  if (by('IN_PROGRESS').length) {
    if (project.status === 'PAUSED') out.push('_Project is paused; these tasks are on hold._');
    out.push(
      by('IN_PROGRESS')
        .map((t) => `${line(t)} — scope: ${(t.scope ?? []).length ? t.scope.join(', ') : 'exclusive'} — fix attempts ${t.fix_attempts}/${project.limits.max_fix_attempts}. If no session is working on it, it was interrupted; resume with /orkestr:build ${t.id}.`)
        .join('\n'),
    );
  } else out.push('- (none)');
  out.push('', '## In review', '');
  out.push(by('REVIEW').length ? by('REVIEW').map(line).join('\n') : '- (none)');
  out.push('', '## Assumptions made without asking', '');
  out.push(assumptionLines(project));
  out.push('', '## Ready to start', '');
  out.push(by('READY').length ? by('READY').map(line).join('\n') : '- (none)');
  out.push('', '## Recent history', '');
  out.push(
    history.length
      ? history.slice(-8).map((h) => `- ${h.ts} ${h.type}${h.entity ? ` ${h.entity}` : ''}${h.to ? ` → ${h.to}` : ''}${h.summary ? ` — ${h.summary}` : ''}`).join('\n')
      : '- (none)',
  );
  out.push('', '## Validation', '');
  if (!validation.errors.length && !validation.warnings.length) out.push('- OK: no problems found.');
  for (const e of validation.errors) out.push(`- ERROR: ${e}`);
  for (const w of validation.warnings) out.push(`- WARNING: ${w}`);
  out.push('');
  return out.join('\n');
}
