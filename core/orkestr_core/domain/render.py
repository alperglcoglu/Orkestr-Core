"""Generated Markdown views and reports, ported from render.mjs (MASTER_SPEC §16).

Views are derived from records and never edited by hand. The text matches the Phase 1
views so a project looks the same whether the plugin or the core manages it. The completion
report is the exception: it separates scope checks from tests (PHASE4_IMPLEMENTATION.md §4).
"""

from __future__ import annotations

from .state import SCOPE_CHECK_COMMAND


def _banner(rid: str) -> str:
    return f"<!-- Generated by orkestr from {rid}.json. Do not edit; change the record through the orkestr state tool. -->\n"


def _list(items, fmt=lambda x: x) -> str:
    return "\n".join(f"- {fmt(x)}" for x in items) if items else "- (none)"


def render_meeting(m: dict) -> str:
    rounds = []
    for r in m["rounds"]:
        lines = []
        for c in r["contributions"]:
            points = "\n" + "\n".join(f"  - {p}" for p in c["key_points"]) if c.get("key_points") else ""
            concerns = f"\n  - Concerns: {'; '.join(c['concerns'])}" if c.get("concerns") else ""
            lines.append(f"- **{c['role']}:** {c['position']}{points}{concerns}")
        rounds.append(f"### Round {r['round']}\n\n" + "\n".join(lines))
    discussion = "\n\n".join(rounds)
    return f"""{_banner(m['id'])}
# {m['id']} — {m['objective']}

- **Date:** {m['date']}
- **Outcome:** {m['outcome']}
- **Decision:** {m.get('decision_id') or '(none)'}
- **Tasks created:** {', '.join(m['task_ids']) if m['task_ids'] else '(none)'}

## Why a meeting

{m['trigger']}

## Context

{m['context']}

## Participants

{_list(m['participants'], lambda p: f"**{p['role']}** — {p['responsibility']}")}

## Discussion

{discussion}

## Options

{_list(m['options'], lambda o: f"**{o['id']} {o['name']}** — {o.get('summary') or ''}")}

## Evaluation criteria

{_list(m['criteria'])}

## Evaluation

{m.get('evaluation') or '(not recorded)'}

## Dissent

{_list(m['dissent'], lambda d: f"**{d['role']}:** {d['objection']}")}

## Open questions

{_list(m['open_questions'])}
"""


def render_decision(d: dict) -> str:
    selected = next((o for o in d["options"] if o.get("id") == d.get("selected_option")), None)
    decided = f" (by {d['decided_by']} at {d['decided_at']})" if d.get("decided_by") else ""
    recovery = f" (recovery for {d['recovery_for']})" if d.get("recovery_for") else ""
    note = f"\n## Founder note\n\n{d['note']}\n" if d.get("note") else ""
    return f"""{_banner(d['id'])}
# {d['id']} — {d['question']}

- **Date:** {d['date']}
- **Project:** {d['project']}
- **Approval status:** {d['approval_status']}{decided}
- **Meeting:** {d.get('meeting_id') or '(none)'}{recovery}
- **Founder required:** {'yes' if d.get('founder_required') else 'no'}
- **Participants:** {', '.join(d['participants'])}
- **Follow-up tasks:** {', '.join(d['task_ids']) if d['task_ids'] else '(none)'}

## Context

{d['context']}

## Options considered

{_list(d['options'], lambda o: f"**{o['id']} {o['name']}** — {o.get('summary') or ''}")}

## Evaluation criteria

{_list(d['criteria'])}

## Selected option

{f"**{selected['id']} {selected['name']}**" if selected else '(none — waiting for the founder)'}

## Rationale

{d.get('rationale') or '(not recorded)'}

## Trade-offs

{_list(d['tradeoffs'])}

## Material objections

{_list(d['objections'], lambda o: f"**{o['role']}:** {o['objection']}")}

## Risks

{_list(d['risks'])}
{note}"""


def render_review(r: dict) -> str:
    confirmed = [f for f in r["findings"] if f["status"] == "confirmed"]
    suspected = [f for f in r["findings"] if f["status"] == "suspected"]

    def fmt(f):
        component = f" ({f['component']})" if f.get("component") else ""
        return f"**[{f['severity']}] {f['title']}**{component}\n  - Evidence: {f['evidence']}\n  - Recommendation: {f.get('recommendation') or '(none)'}"

    def check(c):
        summary = f": {c['summary']}" if c.get("summary") else ""
        return f"`{c['command']}` — {c['result']}{summary}"

    return f"""{_banner(r['id'])}
# {r['id']} — Review: {r['scope']}

- **Date:** {r['date']}
- **Task:** {r.get('task_id') or '(none)'}
- **Reviewers:** {', '.join(r['reviewers'])}
- **Verdict:** {r['verdict']}

## Checks actually run

{_list(r['checks_run'], check)}

## Confirmed findings (verified)

{_list(confirmed, fmt)}

## Suspected findings (not verified)

{_list(suspected, fmt)}

## Assumptions

{_list(r['assumptions'])}
"""


def render_retro(r: dict) -> str:
    return f"""{_banner(r['id'])}
# {r['id']} — Retrospective: {r['scope']}

- **Date:** {r['date']}

## What went well

{_list(r['went_well'])}

## What went badly

{_list(r['went_badly'])}

## Incorrect assumptions

{_list(r['incorrect_assumptions'])}

## Was the decomposition appropriate?

{r.get('decomposition_assessment') or '(not assessed)'}

## Did meetings improve decisions?

{r.get('meeting_assessment') or '(not assessed)'}

## Lessons (with evidence)

{_list(r['lessons'], lambda l: f"{l['lesson']} — evidence: {l['evidence']}")}

## Proposed changes (not applied; need review)

{_list(r['proposed_changes'])}
"""


RENDERERS = {"meetings": render_meeting, "decisions": render_decision, "reviews": render_review, "retros": render_retro}


def _assumption_lines(project: dict) -> str:
    items = project.get("assumptions") or []
    if not items:
        return "- (none)"
    return "\n".join(f"- [{a['impact']}] {a['text']}{f" ({a['task']})" if a.get('task') else ''}" for a in items)


def render_report(project: dict, tasks: list[dict], approvals: list[dict], decisions: list[dict], validation: dict, usage: dict | None = None) -> str:
    by = lambda s: [t for t in tasks if t["status"] == s]  # noqa: E731
    reason = f" — {project['status_reason']}" if project.get("status_reason") else ""
    out = [f"# Orkestr completion report — {project['name']}", ""]
    out.append(f"- **Project status:** {project['status']}{reason}")
    out.append(f"- **Autonomy:** {project.get('autonomy') or 'supervised'}")
    counts = ", ".join(f"{s} {len(by(s))}" for s in ("COMPLETED", "IN_PROGRESS", "REVIEW", "READY", "BACKLOG", "BLOCKED", "FAILED", "CANCELLED"))
    out += [f"- **Tasks:** {counts} (total {len(tasks)})", ""]

    out += ["## What was done", ""]
    done = by("COMPLETED")
    out.append("\n".join(f"- {t['id']} — {t['title']} (owner: {t['owner']})" for t in done) if done else "- (no completed tasks)")

    # Scope checks are bookkeeping, not tests (phase2/FINDINGS.md #13), so they are listed apart.
    runs = [(t, e) for t in tasks for e in t["evidence"] if e["type"] in ("test", "check") and e["result"] != "not_run"]
    checks = [(t, e) for t, e in runs if e.get("command") != SCOPE_CHECK_COMMAND]
    scopes = [(t, e) for t, e in runs if e.get("command") == SCOPE_CHECK_COMMAND]
    out += ["", "## Tests and checks run", ""]
    out.append("\n".join(f"- {t['id']}: `{e.get('command')}` → {e['result']} — {e['summary']}" for t, e in checks) if checks else "- (no checks recorded)")
    if scopes:
        out += ["", "### Scope checks", "", "\n".join(f"- {t['id']}: {e['result']} — {e['summary']}" for t, e in scopes)]
    not_run = [f"- {t['id']}: not run — {e['summary']}" for t in tasks for e in t["evidence"] if e["result"] == "not_run"]
    if not_run:
        out += ["", "### Not run", "", "\n".join(not_run)]

    out += ["", "## Decisions", ""]
    out.append(
        "\n".join(f"- {d['id']} [{d['approval_status']}{', by ' + d['decided_by'] if d.get('decided_by') else ''}] {d['question']}" for d in decisions)
        if decisions
        else "- (none)"
    )
    out += ["", "## Assumptions", "", _assumption_lines(project)]

    out += ["", "## Unresolved", ""]
    open_items = [
        *[f"- {t['id']} FAILED — {(t.get('failure') or {}).get('error')}; next: {(t.get('failure') or {}).get('next_action')}" for t in by("FAILED")],
        *[f"- {t['id']} BLOCKED — {t.get('blocked_reason')}" for t in by("BLOCKED")],
        *[f"- {t['id']} {t['status']} — {t['title']}" for t in (*by("IN_PROGRESS"), *by("REVIEW"), *by("READY"), *by("BACKLOG"))],
    ]
    out.append("\n".join(open_items) if open_items else "- (none)")

    out += ["", "## Needs the founder", ""]
    founder = [
        *[f"- Approve or reject {a['id']} [{a['category']}]: {a['action']}" for a in approvals if a["status"] == "PENDING"],
        *[f"- Decide {d['id']}: {d['question']}" for d in decisions if d["approval_status"] in ("PROPOSED", "NEEDS_FOUNDER")],
        *[
            f"- {t['id']} could not be fixed within limits: retry, change approach, or cancel"
            for t in by("FAILED")
            if "Founder" in ((t.get("failure") or {}).get("next_action") or "")
        ],
        *[f"- Authorize or drop {t['id']}: {t['title']}" for t in tasks if not t["authorized"] and t["status"] not in ("CANCELLED", "COMPLETED")],
    ]
    out.append("\n".join(founder) if founder else "- Nothing.")

    if usage is not None:
        out += ["", "## Agent usage (as reported by the executor)", ""]
        out.append(f"- Agent calls: {usage['calls']} (failed: {usage['failed']})")
        out.append(f"- Turns: {usage['num_turns']}")
        out.append(f"- Tokens: {usage['input_tokens']} in / {usage['output_tokens']} out")
        cost = usage.get("reported_cost_usd")
        out.append(
            f"- Reported cost: ${cost:.4f} (an estimate from Claude Code; with a subscription this is plan usage, not a charge)"
            if cost
            else "- Reported cost: not reported"
        )

    out += ["", "## Validation", ""]
    out.append("\n".join(f"- ERROR: {e}" for e in validation["errors"]) if validation["errors"] else "- OK")
    out.append("")
    return "\n".join(out)


def render_status(project: dict, tasks: list[dict], approvals: list[dict], decisions: list[dict], history: list[dict], validation: dict, run: dict | None = None) -> str:
    by = lambda s: [t for t in tasks if t["status"] == s]  # noqa: E731
    line = lambda t: f"- {t['id']} — {t['title']} (owner: {t['owner']})"  # noqa: E731
    limits = project["limits"]
    reason = f" — {project['status_reason']}" if project.get("status_reason") else ""
    out = [f"# Orkestr status — {project['name']}", ""]
    out.append(f"- **Project status:** {project['status']}{reason}")
    out.append(f"- **Goal:** {project['goal']}")
    out.append(f"- **Autonomy:** {project.get('autonomy') or 'supervised'}")
    out.append(f"- **Managed by:** {project.get('managed_by') or 'plugin'}")
    out.append(
        f"- **Limits:** {limits['max_meeting_participants']} meeting participants, {limits['max_discussion_rounds']} discussion rounds, "
        f"{limits['max_fix_attempts']} fix attempts, {limits.get('max_recovery_meetings', 1)} recovery meeting(s) per task, "
        f"{limits.get('max_parallel_tasks', 1)} parallel task(s)"
    )
    if run:
        out.append(f"- **Latest run:** {run['id']} {run['status']}{(' — ' + run['status_reason']) if run.get('status_reason') else ''} ({run['agent_calls']} agent call(s))")
    out.append("")

    out += ["## Task counts", "", "| State | Count |", "| :- | -: |"]
    for s in ("BACKLOG", "READY", "IN_PROGRESS", "BLOCKED", "REVIEW", "FAILED", "COMPLETED", "CANCELLED"):
        out.append(f"| {s} | {len(by(s))} |")
    out += [f"| **Total** | {len(tasks)} |", ""]

    pending = [a for a in approvals if a["status"] == "PENDING"]
    waiting = [d for d in decisions if d["approval_status"] in ("PROPOSED", "NEEDS_FOUNDER")]
    unauthorized = [t for t in tasks if not t["authorized"] and t["status"] not in ("CANCELLED", "COMPLETED")]
    out += ["## Needs founder attention", "", "### Pending approvals", ""]
    out.append(
        "\n".join(f"- {a['id']} [{a['category']}] {a['action']}{f" (task {a['task_id']})" if a.get('task_id') else ''} — reason: {a['reason']}" for a in pending)
        if pending
        else "- (none)"
    )
    out += ["", "### Decisions waiting for the founder", ""]
    out.append("\n".join(f"- {d['id']} [{d['approval_status']}] {d['question']}" for d in waiting) if waiting else "- (none)")
    out += ["", "### Tasks waiting for authorization", ""]
    out.append(
        "\n".join(f"- {t['id']} — {t['title']} (source: {t['source']['type']}{', decision ' + t['decision_id'] if t.get('decision_id') else ''})" for t in unauthorized)
        if unauthorized
        else "- (none)"
    )
    out.append("")

    out += ["## Blocked", ""]
    out.append("\n".join(f"{line(t)}\n  - Reason: {t.get('blocked_reason')}" for t in by("BLOCKED")) if by("BLOCKED") else "- (none)")
    out += ["", "## Failed", ""]
    out.append(
        "\n".join(f"{line(t)}\n  - Error: {(t.get('failure') or {}).get('error')}\n  - Next action: {(t.get('failure') or {}).get('next_action')}" for t in by("FAILED"))
        if by("FAILED")
        else "- (none)"
    )
    out += ["", "## In progress", ""]
    if by("IN_PROGRESS"):
        if project["status"] == "PAUSED":
            out.append("_Project is paused; these tasks are on hold._")
        out.append(
            "\n".join(
                f"{line(t)} — scope: {', '.join(t['scope']) if t.get('scope') else 'exclusive'} — fix attempts {t['fix_attempts']}/{limits['max_fix_attempts']}."
                for t in by("IN_PROGRESS")
            )
        )
    else:
        out.append("- (none)")
    out += ["", "## In review", ""]
    out.append("\n".join(line(t) for t in by("REVIEW")) if by("REVIEW") else "- (none)")
    out += ["", "## Assumptions made without asking", "", _assumption_lines(project)]
    out += ["", "## Ready to start", ""]
    out.append("\n".join(line(t) for t in by("READY")) if by("READY") else "- (none)")
    out += ["", "## Recent history", ""]

    def hist(h):
        entity = f" {h['entity']}" if h.get("entity") else ""
        to = f" → {h['to']}" if h.get("to") else ""
        summary = f" — {h['summary']}" if h.get("summary") else ""
        return f"- {h['ts']} {h['type']}{entity}{to}{summary}"

    out.append("\n".join(hist(h) for h in history[-8:]) if history else "- (none)")
    out += ["", "## Validation", ""]
    if not validation["errors"] and not validation["warnings"]:
        out.append("- OK: no problems found.")
    out += [f"- ERROR: {e}" for e in validation["errors"]]
    out += [f"- WARNING: {w}" for w in validation["warnings"]]
    out.append("")
    return "\n".join(out)
